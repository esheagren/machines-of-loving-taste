// Bundle the current sanitizer so Vercel's require hook does not need to require
// the ESM-only htmlparser2 dependency from CommonJS. Keep current security fixes.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
const version = JSON.parse(readFileSync('node_modules/sanitize-html/package.json','utf8')).version;
await build({
  entryPoints: ['node_modules/sanitize-html/index.js'],
  outfile: 'lib/sanitize.cjs', bundle: true, minify: true,
  platform: 'node', format: 'cjs', target: 'node22',
  banner: {js: `// Generated by src/build-sanitizer.js from sanitize-html ${version}. Do not edit.`},
});
